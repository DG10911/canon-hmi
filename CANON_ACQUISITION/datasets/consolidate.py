#!/usr/bin/env python3
"""Merge the per-source dataset discovery files into one registry + a pull script.

Reads hf_datasets.json, kaggle_datasets.json, github_datasets.json (whichever
exist) and writes:
  dataset_registry.json   one registry, deduped by url, with a per-source summary
  pull_datasets.sh        commands to fetch the public/clonable ones (gated ones
                          are listed as comments with their request URL)

Pure stdlib.  python3 consolidate.py
"""
from __future__ import annotations
import json
import os
from datetime import datetime, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
FILES = ["hf_datasets.json", "kaggle_datasets.json", "github_datasets.json"]


def main():
    all_rows, per_source = [], {}
    seen = set()
    for fn in FILES:
        path = os.path.join(HERE, fn)
        if not os.path.exists(path):
            continue
        rows = json.load(open(path, encoding="utf-8"))
        rows = rows if isinstance(rows, list) else rows.get("datasets", [])
        kept = 0
        for r in rows:
            url = r.get("url")
            if not url or url in seen:
                continue
            seen.add(url)
            all_rows.append(r)
            kept += 1
        per_source[fn.replace("_datasets.json", "")] = kept

    def tally(key):
        out = {}
        for r in all_rows:
            out[r.get(key, "?")] = out.get(r.get(key, "?"), 0) + 1
        return dict(sorted(out.items()))

    registry = {
        "generated": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "discovery_method": "web-verified (HuggingFace / Kaggle / GitHub / official)",
        "note": "Real, reachable public datasets for CANON training/augmentation. Gated "
                "ICS datasets (SWaT/WADI/HAI/Morris) are marked access=request/gated with "
                "their real registration URL — never claimed directly downloadable. Respect "
                "each dataset's license before redistribution.",
        "total": len(all_rows),
        "by_source": per_source,
        "by_category": tally("category"),
        "by_access": tally("access"),
        "datasets": all_rows,
    }
    reg_path = os.path.join(HERE, "dataset_registry.json")
    json.dump(registry, open(reg_path, "w"), indent=2, sort_keys=True)

    # pull script
    lines = ["#!/usr/bin/env bash",
             "# Auto-generated by consolidate.py — fetch the public CANON datasets.",
             "# Requires: `hf` (pip install -U huggingface_hub; `huggingface-cli` is deprecated) and `kaggle`",
             "# (pip install kaggle + ~/.kaggle/kaggle.json). Gated datasets are listed as",
             "# comments with their request URL — request access, don't scrape.",
             "set -euo pipefail", 'DEST="${1:-./downloads}"', 'mkdir -p "$DEST"', ""]
    for r in all_rows:
        acc = (r.get("access") or "").lower()
        ident, src = r.get("identifier"), r.get("source")
        header = f'# [{r.get("category")}] {r.get("name")}  ({r.get("license")})'
        if acc in ("request", "gated"):
            lines += [header, f'#   REQUEST ACCESS: {r.get("url")}', ""]
            continue
        if src == "huggingface":
            lines += [header, f'hf download {ident} --repo-type dataset --local-dir "$DEST/{_slug(ident)}" || true', ""]
        elif src == "kaggle":
            lines += [header, f'kaggle datasets download -d {ident} -p "$DEST/{_slug(ident)}" --unzip || true', ""]
        elif src in ("github", "official") and r.get("url", "").startswith("https://github.com/"):
            lines += [header, f'git clone --depth 1 {r.get("url")} "$DEST/{_slug(ident or r.get("name"))}" || true', ""]
        else:
            lines += [header, f'#   manual: {r.get("url")}', ""]
    sh_path = os.path.join(HERE, "pull_datasets.sh")
    open(sh_path, "w").write("\n".join(lines) + "\n")
    os.chmod(sh_path, 0o755)

    print(f"registry: {reg_path}  ({registry['total']} datasets)")
    print("by_source :", per_source)
    print("by_category:", registry["by_category"])
    print("by_access :", registry["by_access"])
    print(f"pull script: {sh_path}")


def _slug(s: str) -> str:
    return "".join(c if c.isalnum() or c in "-_" else "_" for c in (s or "ds"))


if __name__ == "__main__":
    main()
